"""Wire format. The only thing both sides are allowed to agree on.

Everything crossing the network is one of four messages, each carrying a schema
version so an old scheduler and a new agent can detect the mismatch instead of
misreading each other's fields.

Two-phase replies
-----------------
A command gets *two* replies: ACCEPTED as soon as the agent has taken it, then
COMPLETED or FAILED when the motion is actually over. A pick can take thirty
seconds, and a single blocking reply cannot distinguish "still moving" from
"the workstation died" -- which are opposite situations for a scheduler.
REJECTED is the one-phase case: refused before anything moved.

Idempotency
-----------
`command_id` is generated by the client and echoed in every reply. MQTT at
QoS 1 is at-least-once, so a flaky link will redeliver commands; the agent
remembers recently seen ids and re-sends the previous reply rather than picking
the object up twice.
"""

from __future__ import annotations

import json
import time
import uuid
from dataclasses import asdict, dataclass, field
from enum import Enum

SCHEMA_VERSION = 1


class ReplyStatus(str, Enum):
    ACCEPTED = "accepted"    # taken, now running; a second reply will follow
    COMPLETED = "completed"  # finished successfully
    FAILED = "failed"        # started and did not finish
    REJECTED = "rejected"    # refused; nothing moved


class RobotState(str, Enum):
    OFFLINE = "OFFLINE"    # agent not reachable (published by the broker's LWT)
    STARTING = "STARTING"  # agent up, SDK not connected yet
    IDLE = "IDLE"          # ready for work
    BUSY = "BUSY"          # executing a task
    ERROR = "ERROR"        # last task failed; still accepting commands
    ESTOP = "ESTOP"        # latched stop; refuses motion until reset


def now() -> float:
    return time.time()


def new_id() -> str:
    return uuid.uuid4().hex[:16]


@dataclass
class Command:
    """Laptop -> agent. A verb and its arguments, nothing robot-specific."""

    command: str
    params: dict = field(default_factory=dict)
    command_id: str = field(default_factory=new_id)
    reply_to: str = ""
    timeout_s: float = 120.0
    ts: float = field(default_factory=now)
    v: int = SCHEMA_VERSION

    def to_bytes(self) -> bytes:
        return json.dumps(asdict(self), separators=(",", ":")).encode()

    @staticmethod
    def from_bytes(raw: bytes) -> "Command":
        d = json.loads(raw.decode())
        return Command(
            command=d["command"],
            params=d.get("params") or {},
            command_id=d.get("command_id", new_id()),
            reply_to=d.get("reply_to", ""),
            timeout_s=float(d.get("timeout_s", 120.0)),
            ts=float(d.get("ts", now())),
            v=int(d.get("v", 0)),
        )


@dataclass
class Reply:
    """Agent -> the one laptop that asked."""

    command_id: str
    status: ReplyStatus
    robot_id: str = ""
    result: dict = field(default_factory=dict)
    error: dict | None = None
    ts: float = field(default_factory=now)
    v: int = SCHEMA_VERSION

    @property
    def ok(self) -> bool:
        return self.status in (ReplyStatus.ACCEPTED, ReplyStatus.COMPLETED)

    @property
    def terminal(self) -> bool:
        """True once no further reply will arrive for this command."""
        return self.status is not ReplyStatus.ACCEPTED

    def to_bytes(self) -> bytes:
        d = asdict(self)
        d["status"] = self.status.value
        return json.dumps(d, separators=(",", ":")).encode()

    @staticmethod
    def from_bytes(raw: bytes) -> "Reply":
        d = json.loads(raw.decode())
        return Reply(
            command_id=d["command_id"],
            status=ReplyStatus(d["status"]),
            robot_id=d.get("robot_id", ""),
            result=d.get("result") or {},
            error=d.get("error"),
            ts=float(d.get("ts", now())),
            v=int(d.get("v", 0)),
        )


@dataclass
class StateMessage:
    """Agent -> everyone, retained. The robot's own view of itself.

    `capabilities` is what makes the scheduler robot-agnostic: it asks what a
    robot can do rather than being told at build time, so a new robot type on
    the bus is immediately usable.
    """

    robot_id: str
    model: str
    state: RobotState
    capabilities: list = field(default_factory=list)
    current_task: str | None = None
    current_command_id: str | None = None
    last_error: dict | None = None
    sdk_connected: bool = False
    # The robot's own view of itself -- joints, mode, errors. Carried on the
    # retained state topic so an observer sees live motion without having to
    # poll GetRobotState; that reply is for callers, this is for watchers.
    telemetry: dict = field(default_factory=dict)
    agent_version: str = "1.0.0"
    ts: float = field(default_factory=now)
    v: int = SCHEMA_VERSION

    def to_bytes(self) -> bytes:
        d = asdict(self)
        d["state"] = self.state.value
        return json.dumps(d, separators=(",", ":")).encode()

    @staticmethod
    def from_bytes(raw: bytes) -> "StateMessage":
        d = json.loads(raw.decode())
        return StateMessage(
            robot_id=d["robot_id"],
            model=d.get("model", "unknown"),
            state=RobotState(d.get("state", "OFFLINE")),
            capabilities=d.get("capabilities") or [],
            current_task=d.get("current_task"),
            current_command_id=d.get("current_command_id"),
            last_error=d.get("last_error"),
            sdk_connected=bool(d.get("sdk_connected", False)),
            telemetry=d.get("telemetry") or {},
            agent_version=d.get("agent_version", "?"),
            ts=float(d.get("ts", now())),
            v=int(d.get("v", 0)),
        )


@dataclass
class Presence:
    """Retained. Written by the agent on connect, by the broker on death."""

    robot_id: str
    online: bool
    ts: float = field(default_factory=now)
    v: int = SCHEMA_VERSION

    def to_bytes(self) -> bytes:
        return json.dumps(asdict(self), separators=(",", ":")).encode()

    @staticmethod
    def from_bytes(raw: bytes) -> "Presence":
        d = json.loads(raw.decode())
        return Presence(
            robot_id=d["robot_id"],
            online=bool(d.get("online", False)),
            ts=float(d.get("ts", now())),
            v=int(d.get("v", 0)),
        )
